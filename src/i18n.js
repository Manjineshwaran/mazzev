export function translate(lang, key, vars) {
  const table = STRINGS[lang] || en
  let text = table[key] ?? en[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, v)
    }
  }
  return text
}
